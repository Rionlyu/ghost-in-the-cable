import {test,expect} from '@playwright/test';

test('LIVE production · a stale tab cannot spend the next ticket query and refreshes without retrying', async({page,context,request})=>{
 test.skip(Reflect.get(globalThis,'process').env.LIVE_API!=='1','Actual Qiskit server required; no HTTP mocks.');
 await page.goto('/');
 await page.getByRole('button',{name:'Open the shop',exact:true}).click();
 await page.getByRole('button',{name:'Skip to repairs',exact:true}).click();
 await expect(page.locator('.paper-ticket')).toBeVisible();
 const id=await page.evaluate(()=>localStorage.getItem('ghost-in-the-cable-shift'));
 const path=`/api/shifts/${encodeURIComponent(id!)}`;
 const stale=await context.newPage();
 await stale.goto('/');
 await expect(stale.locator('.paper-ticket')).toBeVisible();
 await stale.locator('[data-tool="z"]').click();
 await page.locator('[data-tool="z"]').click();
 await page.locator('[data-action="probe"]').click();
 await expect(page.getByRole('heading',{name:'Adjust the repair.'})).toBeVisible();
 const first=await(await request.get(path)).json();
 if(first.reading.bits==='1')await page.getByRole('switch',{name:'Flip bit',exact:true}).click();
 await page.locator('[data-action="diagnose"]').click();
 await expect(page.getByRole('heading',{name:'It works.'})).toBeVisible();
 await page.locator('[data-action="next"]').click();
 const before=await(await request.get(path)).json();
 expect(before.phase).toBe('choose_tool');
 expect(before.ticket_index).toBe(1);
 const attempts:unknown[]=[];
 stale.on('request',r=>{if(r.method()==='POST'&&new URL(r.url()).pathname===path+'/probe')attempts.push(r.postDataJSON())});
 const rejected=stale.waitForResponse(r=>new URL(r.url()).pathname===path+'/probe'&&r.request().method()==='POST');
 await stale.locator('[data-action="probe"]').click();
 expect((await rejected).status()).toBe(409);
 await expect(stale.locator('.paper-ticket')).toContainText(before.ticket.title);
 await expect(stale.getByRole('alert')).toContainText('refreshed');
 expect(await(await request.get(path)).json()).toEqual(before);
 expect(attempts).toHaveLength(1);
 await stale.screenshot({path:`tests/evidence/live-stale-tab-${stale.viewportSize()!.width}.png`,fullPage:true});
 await stale.locator('[data-tool="x"]').click();
 await stale.locator('[data-action="probe"]').click();
 await expect(stale.getByRole('heading',{name:'Adjust the repair.'})).toBeVisible();
 const after=await(await request.get(path)).json();
 expect(after.reading.tool).toBe('x');
 expect(after.revision).toBe(before.revision+1);
 await stale.close();
});
